"""Portrait index and asset integrity.

The images are generated by scripts/fetch_portraits.py and committed, so these tests
guard the contract the dashboard relies on: every indexed portrait exists, still
belongs to the candidate the forecast names, and carries a licence for attribution.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

IDX = ROOT / "public" / "portraits" / "index.json"
FORECAST = json.loads((ROOT / "output" / "forecast.json").read_text())

pytestmark = pytest.mark.skipif(not IDX.exists(), reason="portraits have not been generated")


def _index() -> dict:
    return json.loads(IDX.read_text())


def test_index_matches_forecast_names_and_files_exist():
    d = _index()
    races = {r["id"]: r for r in FORECAST["races"]}
    assert d["races"], "no race portraits indexed"
    for rid, sides in d["races"].items():
        assert rid in races, f"index references unknown race {rid}"
        for side, entry in sides.items():
            assert side in ("d", "r")
            # the guard the dashboard applies: a renamed candidate must not keep an old face
            assert entry["name"] == races[rid][f"{side}_cand"]
            path = ROOT / "public" / entry["img"].lstrip("/")
            assert path.exists(), f"missing image {entry['img']}"
            assert path.stat().st_size > 1000, f"suspiciously small image {entry['img']}"


def test_portraits_carry_attribution():
    d = _index()
    entries = list(d["candidates"].values())
    assert entries
    for e in entries:
        assert e["article_url"].startswith("https://en.wikipedia.org/wiki/")
        assert e["img"].startswith("/portraits/") and e["img"].endswith(".webp")
    licensed = sum(1 for e in entries if e.get("license"))
    # Wikimedia occasionally lacks licence metadata; the overwhelming majority must have it
    assert licensed >= 0.9 * len(entries), f"only {licensed}/{len(entries)} carry a licence"


def test_served_portraits_match_the_index(tmp_path, monkeypatch):
    import importlib

    from fastapi.testclient import TestClient

    monkeypatch.setenv("LIVE_STATE_PATH", str(tmp_path / "state.json"))
    monkeypatch.setenv("LIVE_OUT_PATH", str(tmp_path / "live.json"))
    monkeypatch.setenv("LIVE_SOURCE", "none")

    import server.app as sapp
    sapp = importlib.reload(sapp)
    d = _index()
    img = next(iter(d["candidates"].values()))["img"]
    with TestClient(sapp.app) as client:
        assert client.get("/portraits/index.json").status_code == 200
        r = client.get(img)
        assert r.status_code == 200 and r.headers["content-type"] == "image/webp"
